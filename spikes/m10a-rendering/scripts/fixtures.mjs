export function buildFixtureSet() {
  const fixtures = specifications.map(({ id, make, expected }) => {
    const bytes = make()
    const record = {
      id,
      file: `${id}.glb`,
      url: `/fixtures/${id}.glb`,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      byteLength: bytes.length,
      logicalId: `fixture-${id}`,
      generator,
      provenance: 'Self-authored geometry, animation and checker pixels; no external source asset.',
      expected,
    }
    return { bytes, record }
  })
  const manifest = Object.fromEntries(fixtures.map(({ record }) => [record.id, record]))
  return { fixtures, manifest, manifestText: `${JSON.stringify(manifest, null, 2)}\n` }
}

export async function checkReproducibility() {
  const first = buildFixtureSet()
  const second = buildFixtureSet()
  if (first.manifestText !== second.manifestText) throw new Error('Fixture manifest generation is not deterministic')
  for (let index = 0; index < first.fixtures.length; index += 1) {
    const fixture = first.fixtures[index]
    if (!fixture.bytes.equals(second.fixtures[index].bytes)) throw new Error(`${fixture.record.id}: generation is not deterministic`)
    const committed = await readFile(resolve(root, 'public/fixtures', fixture.record.file))
    if (!fixture.bytes.equals(committed)) throw new Error(`${fixture.record.id}: checked-in bytes differ from generator`)
  }
  if (await readFile(resolve(root, 'src/fixtures.generated.json'), 'utf8') !== first.manifestText) {
    throw new Error('Checked-in manifest differs from generator')
  }
  return first
}

async function main() {
  if (process.argv.includes('--check')) {
    const { fixtures } = await checkReproducibility()
    console.log(JSON.stringify({ reproducible: true, fixtures: fixtures.map(({ record }) => ({ id: record.id, byteLength: record.byteLength, sha256: record.sha256 })) }, null, 2))
    return
  }
  const { fixtures, manifestText } = buildFixtureSet()
  await mkdir(resolve(root, 'public/fixtures'), { recursive: true })
  await mkdir(resolve(root, 'src'), { recursive: true })
  for (const { bytes, record } of fixtures) await writeFile(resolve(root, 'public/fixtures', record.file), bytes)
  await writeFile(resolve(root, 'src/fixtures.generated.json'), manifestText)
  console.log(`Generated ${fixtures.length} fixed M10A spike fixtures.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main()
